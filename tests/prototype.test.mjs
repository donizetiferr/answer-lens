const read = path => readFile(join(ROOT, COLLECTION, path), 'utf8');
const digest = text => createHash('sha256').update(text).digest('hex');
class MemoryStorage {
  data = new Map(); calls = [];
  getItem(key) { this.calls.push(['get', key]); return this.data.get(key) ?? null; }
  setItem(key, value) { this.calls.push(['set', key]); this.data.set(key, value); }
  removeItem(key) { this.calls.push(['remove', key]); this.data.delete(key); }
  clear() { assert.fail('Origin-wide deletion is forbidden'); }
}
function seed() {
  const storage = new MemoryStorage();
  storage.data.set(rootStorage.STORAGE_KEY, JSON.stringify(beginBlind(demoSession(true), { seed: 13, now: '2026-09-21T07:00:00.000Z' })));
  storage.data.set(rootStorage.LEGACY_KEY, JSON.stringify({ ...legacySession(), remember: true }));
  return storage;
}
