test('opening, saving, opting out and resetting preview never reads or modifies real-app keys', () => {
  const storage = seed(); const before = new Map(storage.data);
  assert.equal(previewStorage.loadLocal(() => storage).session, null);
  assert.equal(previewStorage.loadLegacy(() => storage).session, null);
  assert.equal(previewStorage.saveLocal(demoSession(true), () => storage, null).ok, true);
  assert.equal(previewStorage.loadLocal(() => storage).session.synthetic, true);
  assert.equal(previewStorage.clearLocal(() => storage).ok, true);
  assert.deepEqual(storage.data, before);
  assert.ok(storage.calls.every(([, key]) => key === PREVIEW.storageKey || key === PREVIEW.legacyKey));
});
test('preview legacy import is explicit, local to the preview and leaves both legacy records untouched', () => {
  const storage = seed(); const before = new Map(storage.data); const legacy = JSON.stringify({ ...legacySession(), remember: true });
  storage.data.set(PREVIEW.legacyKey, legacy);
  const result = previewStorage.loadLegacy(() => storage);
  assert.equal(result.ok, true); assert.equal(result.session.version, 2); assert.equal(result.session.remember, false);
  result.session.remember = true; assert.equal(previewStorage.saveLocal(result.session, () => storage, null).ok, true);
  for (const [key, value] of before) assert.equal(storage.data.get(key), value);
  assert.equal(storage.data.get(PREVIEW.legacyKey), legacy);
  assert.ok(storage.calls.every(([, key]) => key === PREVIEW.storageKey || key === PREVIEW.legacyKey));
});
