test('local resource manifest binds the actual root and generated bytes', async () => {
  const m = JSON.parse(await read('resources.json'));
  for (const [path, sha] of Object.entries(m.sourceHashes)) assert.equal(digest(await readFile(join(ROOT, path), 'utf8')), sha, path);
  for (const [path, sha] of Object.entries(m.generatedHashes)) assert.equal(digest(await read(path)), sha, path);
  assert.deepEqual(m.isolation, PREVIEW);
  for (const path of ['styles.css', 'icon.svg', 'src/core.js', 'src/demo.js', 'src/output.js']) assert.equal(await read(path), await readFile(join(ROOT, path), 'utf8'));
  assert.equal(await read('src/app.js'), annotatePreviewApp(await readFile(join(ROOT, 'src/app.js'), 'utf8')));
});
